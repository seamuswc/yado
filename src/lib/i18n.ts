const dictionaries: Record<Locale, Dictionary> = { en, ja };

export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale];
}

export function formatPrice(amount: number, locale: Locale): string {
  return new Intl.NumberFormat(locale === "ja" ? "ja-JP" : "en-US", {
    style: "currency",
    currency: "JPY",
    maximumFractionDigits: 0,
  }).format(amount);
}

export function formatDate(iso: string, locale: Locale): string {
  const d = new Date(iso + "T00:00:00");
  return new Intl.DateTimeFormat(locale === "ja" ? "ja-JP" : "en-GB", {
    weekday: "short",
    month: "short",
    day: "numeric",
  }).format(d);
}

/** Date with year, for expiry dates and receipts. */
export function formatDateLong(iso: string, locale: Locale): string {
  const d = new Date(iso.length > 10 ? iso : iso + "T00:00:00");
  return new Intl.DateTimeFormat(locale === "ja" ? "ja-JP" : "en-GB", { year: "numeric", month: "long", day: "numeric" }).format(d);
}

export function nightsBetween(checkIn: string, checkOut: string): number {
  const a = new Date(checkIn + "T00:00:00").getTime();
  const b = new Date(checkOut + "T00:00:00").getTime();
  if (Number.isNaN(a) || Number.isNaN(b)) return 0;
  return Math.max(0, Math.round((b - a) / 86_400_000));
}
